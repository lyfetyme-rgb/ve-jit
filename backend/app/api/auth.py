"""Authentication endpoints.

No credentials are hardcoded. In ``local`` mode users are loaded from
``LOCAL_USERS_JSON`` (bcrypt hashes generated by ``tools/gen_local_user.py``).
In ``oidc`` mode authentication is delegated to the corporate IdP; this
endpoint only reports that fact and ``/me`` still resolves the caller.
"""

import json
from typing import Any

from fastapi import APIRouter, Depends, HTTPException, status

from app.config import settings
from app.schemas.auth import LoginRequest, TokenResponse
from app.security.auth import create_access_token, verify_password
from app.security.principal import Principal, get_current_principal

router = APIRouter(prefix="/api/v1/auth", tags=["auth"])


def _local_users() -> list[dict[str, Any]]:
    raw = (settings.LOCAL_USERS_JSON or "").strip()
    if not raw:
        return []
    try:
        users = json.loads(raw)
    except ValueError as exc:
        raise HTTPException(status_code=503, detail="LOCAL_USERS_JSON is not valid JSON") from exc
    if not isinstance(users, list):
        raise HTTPException(status_code=503, detail="LOCAL_USERS_JSON must be a JSON array")
    return [u for u in users if isinstance(u, dict)]


@router.post("/login", response_model=TokenResponse)
def login(payload: LoginRequest) -> TokenResponse:
    if settings.AUTH_MODE.strip().lower() == "oidc":
        raise HTTPException(
            status_code=status.HTTP_501_NOT_IMPLEMENTED,
            detail="This deployment authenticates through the configured OIDC provider",
        )

    users = _local_users()
    if not users:
        raise HTTPException(
            status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
            detail="Local login is not configured. Set LOCAL_USERS_JSON or use OIDC.",
        )

    match = next((u for u in users if str(u.get("username")) == payload.username), None)
    stored_hash = str((match or {}).get("password_hash") or "")
    if not match or not stored_hash or not verify_password(payload.password, stored_hash):
        # Same generic response for unknown user and wrong password.
        raise HTTPException(status_code=401, detail="Invalid credentials")

    role = str(match.get("role") or "")
    tenants = match.get("tenants") or []
    stores = match.get("stores") or []
    if not isinstance(tenants, list) or not isinstance(stores, list):
        raise HTTPException(status_code=503, detail="Malformed local user record")

    token = create_access_token(
        subject=payload.username,
        role=role,
        tenants=[str(t) for t in tenants],
        stores=[str(s) for s in stores],
    )
    return TokenResponse(access_token=token)


@router.get("/me")
def me(principal: Principal = Depends(get_current_principal)) -> dict[str, Any]:
    """Identity and effective permissions derived only from the verified token."""
    return {
        "subject": principal.subject,
        "role": principal.role,
        "auth_mode": principal.auth_mode,
        "permissions": sorted(principal.permissions),
        "tenants": sorted(principal.tenants),
        "stores": sorted(principal.stores),
    }
